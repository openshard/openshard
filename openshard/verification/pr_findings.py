"""PR findings: fixed, model-free observations about a change from its base to its head.

The merge gate and ``openshard verify`` both know a change's base and head.
This module reads what git says changed between them and reports plain
findings a reviewer should see. It never runs project code, never calls a
model, and keeps no source text: only paths, names and counts.

A finding is an observation, never a verdict. Whether one should fail the
gate is decided by the caller. ``None`` from ``pr_findings`` means "not
checked" (git could not say what changed); an empty list means "checked,
nothing seen".

Findings so far:

* ``large_change`` -- more than ``LARGE_CHANGE_LINES`` lines added plus
  removed, not counting lockfiles. Reviewers stop catching defects past
  about 400 lines, so the finding suggests a split.
* ``junk_files`` -- the change adds files that are almost never meant to be
  committed: merge and patch leftovers, editor swap and backup files, OS
  metadata, logs, bytecode and coverage data.
* ``grader_touched`` -- the change edits what grades it: an existing test
  file (lines changed or removed, or the file deleted or renamed; only adding
  lines, or adding a new test file, is writing tests, not touching them),
  test runner and coverage setup, CI configuration, or lint and type-check
  configuration, including the tool tables of ``pyproject.toml`` and
  ``setup.cfg`` and the check scripts and tool keys of ``package.json``.
  Thresholds (``fail_under``, ``--cov-fail-under``, ``coverageThreshold``)
  live in those files, so they are covered too.
* ``fix_by_deletion`` / ``removed_public_code`` -- the change removes public
  functions or classes, endpoints or tests (``pr_deletions``). It is
  ``fix_by_deletion`` when a commit subject or the given title reads as a bug
  fix (``fix_basis`` says which), else ``removed_public_code``.
* ``new_dependencies`` -- packages the change adds to ``pyproject.toml``,
  ``requirements*.txt`` or ``package.json`` (``pr_dependencies``), plus the
  lockfiles it changed.
"""

from __future__ import annotations

import configparser
import fnmatch
import json
import re
import tomllib
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import Any

KIND_LARGE_CHANGE = "large_change"
KIND_JUNK_FILES = "junk_files"
KIND_GRADER_TOUCHED = "grader_touched"
KIND_FIX_BY_DELETION = "fix_by_deletion"
KIND_REMOVED_PUBLIC_CODE = "removed_public_code"
KIND_NEW_DEPENDENCIES = "new_dependencies"

LARGE_CHANGE_LINES = 400
MAX_PATHS = 5
MAX_DETAIL = 400  # the Platform contract's limit for a finding's text (change_findings.detail)

# Generated by a package manager, not written or reviewed line by line.
LOCKFILE_NAMES = frozenset({
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "bun.lock",
    "poetry.lock", "uv.lock", "Pipfile.lock", "pdm.lock", "Cargo.lock", "Gemfile.lock", "composer.lock",
    "go.sum", "packages.lock.json",
})

# Matched against the file name (``*`` patterns) or any directory on the path (names ending ``/``).
JUNK_PATTERNS: tuple[str, ...] = (
    "*.orig", "*.rej", "*.bak", "*.swp", "*.swo", "*~", ".DS_Store", "Thumbs.db", "desktop.ini",
    "*.log", "nohup.out", "*.pyc", "*.pyo", "__pycache__/", ".coverage", ".coverage.*", "*.tmp",
)


GitShow = Callable[[str, str], "str | None"]  # (rev, posix path) -> file text at rev, or None

# CI configuration: any change to these changes how the change is checked.
CI_CONFIG_PATTERNS: tuple[str, ...] = (
    ".github/workflows/*", ".github/actions/*", ".gitlab-ci.yml", ".gitlab/ci/*", ".circleci/*",
    "azure-pipelines.yml", "bitbucket-pipelines.yml", "Jenkinsfile", ".buildkite/*", ".travis.yml",
    ".pre-commit-config.yaml", "noxfile.py", "tox.ini",
)
# Whole files that configure linting, type checking, test running or coverage.
CHECK_CONFIG_NAMES: tuple[str, ...] = (
    "ruff.toml", ".ruff.toml", ".flake8", "mypy.ini", ".mypy.ini", "pyrightconfig.json", ".pylintrc", "pylintrc",
    ".eslintrc*", "eslint.config.*", ".eslintignore", "biome.json", "biome.jsonc", ".prettierrc*", "tsconfig*.json",
    "pytest.ini", "conftest.py", ".coveragerc", "codecov.yml", ".codecov.yml", "jest.config.*", "vitest.config.*",
    "vitest.workspace.*", "karma.conf.*", ".mocharc*", "phpunit.xml*", ".golangci.yml", ".golangci.yaml",
    ".rubocop.yml", "clippy.toml", "rustfmt.toml",
)
_PYPROJECT_TOOLS = ("ruff", "mypy", "pytest", "coverage", "pyright", "pylint", "flake8", "black", "isort")
_SETUP_CFG_SECTION = re.compile(r"^(flake8|mypy.*|tool:pytest|coverage:.*|pylint.*|isort)$")
_PACKAGE_JSON_KEYS = ("eslintConfig", "jest", "prettier", "vitest", "c8", "nyc", "mocha")
_CHECK_SCRIPT = re.compile(r"^(pre|post)?(test|lint|typecheck|type-check|check|coverage)(:.*)?$")


@dataclass(frozen=True)
class ChangedFile:
    """One path the change touched. ``added``/``removed`` are None for a binary file."""

    path: str  # posix path at head (the old path for a deletion)
    status: str  # A added, M modified, D deleted, R renamed, C copied, T type change
    old_path: str | None = None  # the path at base, for a rename or copy
    added: int | None = None
    removed: int | None = None


@dataclass(frozen=True)
class Finding:
    kind: str
    detail: str  # plain words, no source text
    paths: tuple[str, ...] = ()
    count: int | None = None
    extra: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        detail = self.detail if len(self.detail) <= MAX_DETAIL else self.detail[: MAX_DETAIL - 1] + "…"
        out: dict[str, Any] = {"kind": self.kind, "detail": detail, "paths": list(self.paths[:MAX_PATHS])}
        if self.count is not None:
            out["count"] = self.count
        out.update(self.extra)
        return out


# -- reading the change ---------------------------------------------------------


def _int(text: str) -> int | None:
    return int(text) if text.isdigit() else None


def parse_changes(name_status: str, numstat: str) -> list[ChangedFile]:
    """``ChangedFile``s from ``git diff -z -M --name-status`` and ``--numstat`` output for the same range."""
    counts: dict[str, tuple[int | None, int | None]] = {}
    parts = numstat.split("\0")
    i = 0
    while i < len(parts):
        head = parts[i]
        i += 1
        if not head.strip():
            continue
        fields = head.split("\t")
        if len(fields) < 3:
            continue
        added, removed, path = _int(fields[0]), _int(fields[1]), fields[2]
        if not path:  # a rename: the old and new paths follow as their own fields
            if i + 1 >= len(parts):
                break
            path = parts[i + 1]
            i += 2
        counts[path] = (added, removed)

    files: list[ChangedFile] = []
    parts = name_status.split("\0")
    i = 0
    while i < len(parts):
        code = parts[i]
        i += 1
        if not code:
            continue
        letter = code[0]
        if letter in "RC":
            if i + 1 >= len(parts):
                break
            old, new = parts[i], parts[i + 1]
            i += 2
        else:
            if i >= len(parts):
                break
            old, new = None, parts[i]
            i += 1
        added, removed = counts.get(new, (None, None))
        files.append(ChangedFile(path=new, status=letter, old_path=old, added=added, removed=removed))
    return files


def changed_files(root: Path, base: str, head: str) -> list[ChangedFile] | None:
    """What changed from the merge-base of *base* and *head* to *head*, as the pull request shows it.

    None when git cannot tell (a missing commit, a shallow clone without the base).
    """
    from openshard.util.git import run_git

    rng = f"{base}...{head}"
    name_status = run_git(root, ["diff", "--name-status", "-z", "-M", rng])
    numstat = run_git(root, ["diff", "--numstat", "-z", "-M", rng])
    if name_status is None or numstat is None:
        return None
    return parse_changes(name_status, numstat)


# -- detectors ------------------------------------------------------------------


def _name(path: str) -> str:
    return PurePosixPath(path).name


def is_lockfile(path: str) -> bool:
    return _name(path) in LOCKFILE_NAMES


def large_change(files: Iterable[ChangedFile], limit: int = LARGE_CHANGE_LINES) -> Finding | None:
    """A finding when more than *limit* lines changed outside lockfiles; binary files are counted apart."""
    files = list(files)
    reviewed = [f for f in files if not is_lockfile(f.path)]
    lines = sum((f.added or 0) + (f.removed or 0) for f in reviewed)
    total = sum((f.added or 0) + (f.removed or 0) for f in files)
    binary = sum(1 for f in files if f.added is None and f.removed is None and f.status != "D")
    if lines <= limit:
        return None
    biggest = sorted(reviewed, key=lambda f: (f.added or 0) + (f.removed or 0), reverse=True)
    return Finding(
        kind=KIND_LARGE_CHANGE,
        detail=(f"{lines} lines changed outside lockfiles, over {limit}; reviewers stop catching defects "
                f"past about {limit} lines, so consider splitting this change"),
        paths=tuple(f.path for f in biggest[:MAX_PATHS]),
        count=lines,
        extra={"limit": limit, "lines_with_lockfiles": total, "binary_files": binary},
    )


def _is_junk(path: str) -> bool:
    p = PurePosixPath(path)
    for pattern in JUNK_PATTERNS:
        if pattern.endswith("/"):
            if pattern[:-1] in p.parts[:-1]:
                return True
        elif fnmatch.fnmatchcase(p.name, pattern):
            return True
    return False


def junk_files(files: Iterable[ChangedFile]) -> Finding | None:
    """A finding when the change adds (or renames into place) files that are usually left behind by mistake."""
    junk = [f.path for f in files if f.status in "ARC" and _is_junk(f.path)]
    if not junk:
        return None
    return Finding(
        kind=KIND_JUNK_FILES,
        detail=f"{len(junk)} file{'' if len(junk) == 1 else 's'} that are usually left behind by mistake "
               "(backups, merge leftovers, logs, bytecode)",
        paths=tuple(junk[:MAX_PATHS]),
        count=len(junk),
    )


def _matches(path: str, patterns: tuple[str, ...]) -> bool:
    name = PurePosixPath(path).name
    return any(fnmatch.fnmatchcase(path, p) if "/" in p else fnmatch.fnmatchcase(name, p) for p in patterns)


def _pyproject_tools(text: str | None) -> dict[str, Any] | None:
    try:
        tool = tomllib.loads(text or "").get("tool", {})
    except (tomllib.TOMLDecodeError, AttributeError):
        return None
    return {k: tool.get(k) for k in _PYPROJECT_TOOLS} if isinstance(tool, dict) else None


def _setup_cfg_sections(text: str | None) -> dict[str, dict[str, str]] | None:
    parser = configparser.ConfigParser(interpolation=None)
    try:
        parser.read_string(text or "")
    except configparser.Error:
        return None
    return {s: dict(parser[s]) for s in parser.sections() if _SETUP_CFG_SECTION.match(s)}


def _package_json_checks(text: str | None) -> dict[str, Any] | None:
    try:
        data = json.loads(text or "{}")
    except ValueError:
        return None
    if not isinstance(data, dict):
        return None
    raw = data.get("scripts")
    scripts: dict[str, Any] = raw if isinstance(raw, dict) else {}
    return {"scripts": {k: v for k, v in scripts.items() if _CHECK_SCRIPT.match(k)},
            **{k: data.get(k) for k in _PACKAGE_JSON_KEYS}}


_TOOL_SECTIONS: dict[str, Callable[[str | None], Any]] = {
    "pyproject.toml": _pyproject_tools,
    "setup.cfg": _setup_cfg_sections,
    "package.json": _package_json_checks,
}


def _grader_category(f: ChangedFile, show: GitShow | None, base_rev: str | None, head_rev: str | None) -> str | None:
    """Why *f* is part of what grades the change, or None."""
    from openshard.verification.gaming_signals import is_test_path

    if _matches(f.path, CI_CONFIG_PATTERNS) or (f.old_path and _matches(f.old_path, CI_CONFIG_PATTERNS)):
        return "ci_config"
    if _matches(f.path, CHECK_CONFIG_NAMES) or (f.old_path and _matches(f.old_path, CHECK_CONFIG_NAMES)):
        return "check_config"
    reader = _TOOL_SECTIONS.get(PurePosixPath(f.path).name)
    if reader is not None:
        if show is None or base_rev is None or head_rev is None:
            return None
        before = reader(show(base_rev, f.old_path or f.path)) if f.status != "A" else reader(None)
        after = reader(show(head_rev, f.path)) if f.status != "D" else reader(None)
        # A file that cannot be parsed on either side is not proof of anything; the diff is still visible.
        return "check_config" if before is not None and after is not None and before != after else None
    if is_test_path(f.old_path or f.path):
        if f.status in "DR":
            return "tests_removed" if f.status == "D" else "tests_renamed"
        if f.status == "M" and (f.removed is None or f.removed > 0):
            return "tests_edited"
    return None


def grader_touched(files: Iterable[ChangedFile], show: GitShow | None = None, base_rev: str | None = None,
                   head_rev: str | None = None) -> Finding | None:
    """A finding when the change edits its own tests, CI, or lint, type-check or coverage settings."""
    hits = [(f.path, c) for f in files if (c := _grader_category(f, show, base_rev, head_rev))]
    if not hits:
        return None
    categories = sorted({c for _, c in hits})
    return Finding(
        kind=KIND_GRADER_TOUCHED,
        detail=f"the change edits what checks it ({', '.join(c.replace('_', ' ') for c in categories)})",
        paths=tuple(p for p, _ in hits[:MAX_PATHS]),
        count=len(hits),
        extra={"categories": categories},
    )


def removed_code(files: Iterable[ChangedFile], show: GitShow | None, base_rev: str | None, head_rev: str | None,
                 subjects: Iterable[str] = ()) -> Finding | None:
    """A finding when the change removes public code, endpoints or tests; ``fix_by_deletion`` for a fix."""
    from openshard.verification.pr_deletions import describe, reads_as_fix, removals

    if show is None or base_rev is None or head_rev is None:
        return None
    removed = removals(files, show, base_rev, head_rev)
    if removed is None:
        return None
    basis = reads_as_fix(subjects)
    kind = KIND_FIX_BY_DELETION if basis else KIND_REMOVED_PUBLIC_CODE
    lead = "a change that reads as a bug fix removes " if basis else "the change removes "
    total = sum(removed[k] for k in ("removed_functions", "removed_endpoints", "removed_tests", "deleted_test_files"))
    extra = {k: removed[k] for k in ("removed_functions", "removed_endpoints", "removed_tests", "deleted_test_files",
                                     "names")}
    extra["reads_as_fix"] = basis is not None
    if basis:
        extra["fix_basis"] = basis
    return Finding(kind=kind, detail=lead + describe(removed), paths=tuple(removed["paths"]), count=total,
                   extra=extra)


def names_within(names: list[str], budget: int) -> str:
    """As many of *names* as fit in *budget* characters, then ``+N more`` for the rest; never over budget."""
    shown: list[str] = []
    for i, name in enumerate(names):
        rest = len(names) - i - 1
        candidate = ", ".join([*shown, name]) + (f" +{rest} more" if rest else "")
        if len(candidate) > budget:
            break
        shown.append(name)
    left = len(names) - len(shown)
    if not shown:
        return f"+{left} more"[:budget]
    return ", ".join(shown) + (f" +{left} more" if left else "")


def added_dependencies(files: list[ChangedFile], show: GitShow | None, base_rev: str | None,
                       head_rev: str | None) -> Finding | None:
    """A finding naming each package the change adds, and the lockfiles it changed."""
    from openshard.verification.pr_dependencies import MAX_PACKAGES, new_dependencies

    if show is None or base_rev is None or head_rev is None:
        return None
    packages = new_dependencies(files, show, base_rev, head_rev)
    if not packages:
        return None
    lockfiles = [f.path for f in files if is_lockfile(f.path)]
    lead = f"the change adds {len(packages)} package{'' if len(packages) == 1 else 's'}: "
    return Finding(
        kind=KIND_NEW_DEPENDENCIES,
        detail=lead + names_within([p["name"] for p in packages], MAX_DETAIL - len(lead)),
        paths=tuple(dict.fromkeys(p["manifest"] for p in packages)),
        count=len(packages),
        extra={"packages": packages[:MAX_PACKAGES], "lockfiles": lockfiles[:MAX_PATHS]},
    )


def findings_for(files: list[ChangedFile], show: GitShow | None = None, base_rev: str | None = None,
                 head_rev: str | None = None, subjects: Iterable[str] = ()) -> list[Finding]:
    """Every finding for one change, in a fixed order."""
    found = [large_change(files), junk_files(files), grader_touched(files, show, base_rev, head_rev),
             removed_code(files, show, base_rev, head_rev, subjects),
             added_dependencies(files, show, base_rev, head_rev)]
    return [f for f in found if f is not None]


def pr_findings(root: Path, base: str, head: str, title: str | None = None) -> list[Finding] | None:
    """Findings for the change from *base* to *head* in the checkout at *root*; None when not checked.

    *title* (a pull request title) is read with the commit subjects to tell whether the change is a fix.
    """
    from openshard.util.git import run_git

    files = changed_files(root, base, head)
    fork = run_git(root, ["merge-base", base, head])
    if files is None or not fork:
        return None

    def show(rev: str, path: str) -> str | None:
        return run_git(root, ["show", f"{rev}:{path}"])

    log = run_git(root, ["log", "--format=%s", f"{fork.strip()}..{head}"]) or ""
    subjects = ([title] if title else []) + log.splitlines()
    return findings_for(files, show, fork.strip(), head, subjects)


