"""Generate ``relay/_schema.py`` from ``schema/jobs.json``.

Usage:
    python scripts/gen_schema.py            rewrite relay/_schema.py
    python scripts/gen_schema.py --check    exit 1 if relay/_schema.py is stale
    python scripts/gen_schema.py --stdout   print the generated module
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "schema" / "jobs.json"
TARGET = ROOT / "relay" / "_schema.py"

_TYPES = {"str": "str", "int": "int"}


def load_spec() -> dict:
    with SOURCE.open(encoding="utf-8") as fh:
        spec = json.load(fh)
    if not isinstance(spec, dict) or not isinstance(spec.get("fields"), list):
        raise SystemExit(f"{SOURCE}: expected an object with a 'fields' list")
    return spec


def render(spec: dict) -> str:
    lines = [
        "# Generated by scripts/gen_schema.py from schema/jobs.json.",
        "# Regenerate with: python scripts/gen_schema.py",
        '"""Job record schema (generated)."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        "",
        "class Field(NamedTuple):",
        "    name: str",
        "    kind: type",
        "    required: bool",
        "    default: object",
        "    help: str",
        "",
        "",
        f"SCHEMA_VERSION = {int(spec['version'])}",
        "",
        "FIELDS: tuple[Field, ...] = (",
    ]
    for field in spec["fields"]:
        kind = _TYPES.get(field.get("type"))
        if kind is None:
            raise SystemExit(f"{SOURCE}: unsupported type {field.get('type')!r}")
        required = bool(field.get("required", False))
        default = None if required else field.get("default")
        lines.append(
            f"    Field({field['name']!r}, {kind}, {required!r}, {default!r}, {field.get('help', '')!r}),"
        )
    lines.append(")")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    generated = render(load_spec())
    if "--stdout" in argv:
        sys.stdout.write(generated)
        return 0
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if "--check" in argv:
        if current == generated:
            print(f"{TARGET.relative_to(ROOT)} is up to date.")
            return 0
        print(
            f"{TARGET.relative_to(ROOT)} is out of date with {SOURCE.relative_to(ROOT)}; "
            "run: python scripts/gen_schema.py",
            file=sys.stderr,
        )
        return 1
    TARGET.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
